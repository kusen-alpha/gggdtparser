def _to_ascii(value):
    return value.translate(_AR_DIGITS)


def _numeric_date(match):
    return "%s/%s/%s" % (
        _to_ascii(match.group("Y")),
        _to_ascii(match.group("m")),
        _to_ascii(match.group("d")),
    )


def _named_date(match):
    day = _to_ascii(match.group("d"))
    year = _to_ascii(match.group("Y"))
    return "%s %s %s" % (day, _AR_MONTHS[match.group("name")], year)


def _hijri_named_date(match):
    day = _to_ascii(match.group("d"))
    year = _to_ascii(match.group("Y"))
    month = _AR_HIJRI_MONTHS[match.group("name")]
    date_value = hijri_to_gregorian(int(year), month, int(day))
    if date_value is None:
        return match.group(0)
    return "%s/%s/%s" % (
        date_value.year, date_value.month, date_value.day)


