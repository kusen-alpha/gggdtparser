_HY_UNITS = {
    "վայրկյան": "秒", "վայրկյանում": "秒",
    "րոպե": "分钟", "րոպեում": "分钟",
    "ժամ": "小时", "ժամում": "小时",
    "օր": "天", "օրում": "天",
    "շաբաթ": "周", "շաբաթում": "周",
    "ամիս": "月", "ամսում": "月",
    "տարի": "年", "տարում": "年",
}
_HY_UNIT_RE = (
    r"վայրկյան(?:ում)?|րոպե(?:ում)?|ժամ(?:ում)?|"
    r"օր(?:ում)?|շաբաթ(?:ում)?|ամիս(?:ում)?|տար(?:ի|ում)"
)

_HY_WEEKDAYS = {
    "երկուշաբթի": "周一",
    "երեքշաբթի": "周二",
    "չորեքշաբթի": "周三",
    "հինգշաբթի": "周四",
    "ուրբաթ": "周五",
    "շաբաթ": "周六",
    "կիրակի": "周日",
}
_HY_WEEKDAYS_RE = "|".join(sorted(_HY_WEEKDAYS, key=len, reverse=True))
_HY_WEEKDAYS_DIR_RE = (
    r"երկուշաբթի|երեքշաբթի|չորեքշաբթի|հինգշաբթի|ուրբաթ|կիրակի"
)


def _hy_later(match):
    return "%s%s后" % (match.group(1), _HY_UNITS[match.group(2)])


def _hy_earlier(match):
    return "%s%s前" % (match.group(1), _HY_UNITS[match.group(2)])


