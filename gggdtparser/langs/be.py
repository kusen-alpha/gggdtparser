_BE_UNITS = {
    "секунда": "秒", "секунды": "秒", "секунд": "秒",
    "хвіліна": "分钟", "хвіліны": "分钟", "хвілін": "分钟",
    "гадзіна": "小时", "гадзіны": "小时", "гадзін": "小时",
    "дзень": "天", "дні": "天", "дзён": "天",
    "тыдзень": "周", "тыдні": "周", "тыдняў": "周",
    "месяц": "月", "месяцы": "月", "месяцаў": "月",
    "год": "年", "гады": "年", "гадоў": "年",
}
_BE_UNIT_RE = (
    r"секунд[ауы]?|хвілін[ауы]?|гадзін[ауы]?|"
    r"дзень|дні|дзён|тыдзень|тыдн(?:і|яў)|"
    r"месяц(?:ы|аў)?|год|гады|гадоў"
)


def _be_later(match):
    return "%s%s后" % (match.group("a"), _BE_UNITS[match.group("b")])


def _be_earlier(match):
    return "%s%s前" % (match.group("a"), _BE_UNITS[match.group("b")])


