_KA_UNIT_RE = (
    r"წამ(?:ი|ში)|წუთის|წუთ(?:ი|ში)|საათის|საათ(?:ი|ში)|"
    r"დღის|დღე(?:ში)?|კვირის|კვირა(?:ში)?|თვის|თვე(?:ში)?|წლის|წელ(?:ი|ში)"
)
_KA_UNIT_IN_RE = r"წამში|წუთში|საათში|დღეში|კვირაში|თვეში|წელში"


def _ka_later(match):
    return "%s%s后" % (match.group(1), _KA_UNITS[match.group(2)])


def _ka_earlier(match):
    return "%s%s前" % (match.group(1), _KA_UNITS[match.group(2)])


