_SR_UNITS = {
    "секунд": "秒", "секунде": "秒", "секунди": "秒",
    "секунда": "秒",
    "минут": "分钟", "минута": "分钟",
    "час": "小时", "часа": "小时", "сата": "小时", "сати": "小时",
    "дан": "天", "дана": "天",
    "недеља": "周", "недеље": "周",
    "месец": "月", "месеца": "月", "месеци": "月",
    "година": "年", "године": "年",
}
_SR_UNIT_RE = (
    r"секунд[аеи]?|минут(?:а)?|час(?:а)?|сата|сати|дан(?:а)?|"
    r"недеља|недеље|месец(?:а|и)?|годин[ае]"
)


def _sr_later(match):
    return "%s%s后" % (match.group(1), _SR_UNITS[match.group(2)])


def _sr_earlier(match):
    return "%s%s前" % (match.group(1), _SR_UNITS[match.group(2)])


