"""
泰语（佛历纪年比公历早 543 年）
"""

ACCURATE_REGEX_LIST = []

_THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")


def _to_gregorian(match):
    digits = match.group(1)
    # 泰文数字已在上一步转为 ASCII，这里只处理 ASCII 数字，
    # 避免阿拉伯-印度数字等其他 Unicode 数字被误判为佛历年份。
    if not all('0' <= ch <= '9' for ch in digits):
        return match.group(0)
    year = int(digits)
    # 避免误伤正常的公元纪年
    if year < 2450 or year > 2999:
        return match.group(0)
    return str(year - 543)


