# -*- coding:utf-8 -*-

"""
蒙古语
"""

ACCURATE_REGEX_LIST = []
FUZZY_REGEX_LIST = []

_MN_UNITS = {
    "секунд": "秒", "минут": "分钟", "цаг": "小时",
    "өдөр": "天", "хоног": "周", "долоо хоног": "周",
    "сар": "月", "жил": "年",
}
_MN_UNIT_RE = (
    r"секунд|минут|цаг|өдөр|долоо\s+хоног|хоног|сар|жил"
)

_MN_WEEKDAYS = {
    "даваа": "周一", "Даваа": "周一",
    "мягмар": "周二", "Мягмар": "周二",
    "лхагва": "周三", "Лхагва": "周三",
    "пүрэв": "周四", "Пүрэв": "周四",
    "баасан": "周五", "Баасан": "周五",
    "бямба": "周六", "Бямба": "周六",
    "ням": "周日", "Ням": "周日",
}
_MN_WEEKDAYS_RE = "|".join(sorted(_MN_WEEKDAYS, key=len, reverse=True))

_MN_MONTHS = {
    "нэгдүгээр сар": "1月",
    "хоёрдугаар сар": "2月",
    "гуравдугаар сар": "3月",
    "дөрөвдүгээр сар": "4月",
    "тавдугаар сар": "5月",
    "зургаадугаар сар": "6月",
    "долоодугаар сар": "7月",
    "наймдугаар сар": "8月",
    "есдүгээр сар": "9月",
    "аравдугаар сар": "10月",
    "арваннэгдүгээр сар": "11月",
    "арванхоёрдугаар сар": "12月",
}


def _mn_later(match):
    return "%s%s后" % (match.group("a"), _MN_UNITS[match.group("b")])


def _mn_earlier(match):
    return "%s%s前" % (match.group("a"), _MN_UNITS[match.group("b")])


SUB_TRANSLATE = [
    (r"(?:ирэх|дараагийн)\s+(%s)" % _MN_WEEKDAYS_RE,
     lambda m: "下%s" % _MN_WEEKDAYS[m.group(1)]),
    (r"өнгөрсөн\s+(%s)" % _MN_WEEKDAYS_RE,
     lambda m: "上%s" % _MN_WEEKDAYS[m.group(1)]),
    (r"энэ\s+(%s)" % _MN_WEEKDAYS_RE,
     lambda m: "这%s" % _MN_WEEKDAYS[m.group(1)]),
    (r"өнөөдөр\s+өглөө", "今天 08:00 am"),
    (r"өнөөдөр\s+үд\s+дунд", "今天 12:00 pm"),
    (r"өнөөдөр\s+үдээс\s+хойш", "今天 15:00 pm"),
    (r"өнөөдөр\s+орой", "今天 20:00 pm"),
    (r"өнөөдөр\s+шөнө", "今天 22:00 pm"),
    (r"маргааш\s+өглөө", "明天 08:00 am"),
    (r"өчигдөр\s+орой", "昨天 20:00 pm"),
    (r"шөнө\s+дунд", "12:00 am"),
    (r"(?P<n>\d{1,2})\s*[-–]?\s*р?\s+сар", lambda m: "%s月" % m.group("n")),
]

for _month, _num in _MN_MONTHS.items():
    SUB_TRANSLATE.append((
        r"\b" + _month.replace(" ", r"\s+") + r"\b", _num))

SUB_TRANSLATE += [
    (r"нөгөө\s+маргааш", "后天"),
    (r"нөгөөдөр", "前天"),
    (r"өнөөдөр", "今天"),
    (r"өчигдөр", "昨天"),
    (r"маргааш", "明天"),
    (r"одоо", "刚刚"),
    (r"(?P<a>\d+)\s*(?P<b>%s)(?:ийн|ын|н)?\s+дараа" % _MN_UNIT_RE, _mn_later),
    (r"(?P<a>\d+)\s*(?P<b>%s)(?:ийн|ын|н)?\s+өмнө" % _MN_UNIT_RE, _mn_earlier),
    (r"ирэх\s+долоо\s+хоног", "下周"),
    (r"өнгөрсөн\s+долоо\s+хоног", "上周"),
    (r"ирэх\s+сар", "下个月"),
    (r"өнгөрсөн\s+сар", "上个月"),
    (r"ирэх\s+жил", "明年"),
    (r"өнгөрсөн\s+жил", "去年"),
]

for _weekday in sorted(_MN_WEEKDAYS, key=len, reverse=True):
    SUB_TRANSLATE.append((_weekday, _MN_WEEKDAYS[_weekday]))
