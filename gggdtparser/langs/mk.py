ACCURATE_REGEX_LIST = []
FUZZY_REGEX_LIST = []

_MK_UNITS = {
    "секунда": "秒", "секунди": "秒",
    "минута": "分钟", "минути": "分钟",
    "час": "小时", "часа": "小时", "часови": "小时",
    "ден": "天", "дена": "天",
    "недела": "周", "недели": "周",
    "месец": "月", "месеци": "月",
    "година": "年", "години": "年",
}
_MK_UNIT_RE = (
    r"секунд[аи]|минут[аи]|час(?:а|ови)?|ден(?:а)?|"
    r"недел[аи]|месец(?:и)?|годин[аи]"
)

_MK_WEEKDAYS = {
    "понеделник": "周一",
    "вторник": "周二",
    "среда": "周三",
    "четврток": "周四",
    "петок": "周五",
    "сабота": "周六",
    "недела": "周日",
}
_MK_WEEKDAYS_RE = "|".join(sorted(_MK_WEEKDAYS, key=len, reverse=True))
_MK_WEEKDAYS_DIR_RE = (
    r"понеделник|вторник|среда|четврток|петок|сабота"
)


def _mk_later(match):
    return "%s%s后" % (match.group(1), _MK_UNITS[match.group(2)])


def _mk_earlier(match):
    return "%s%s前" % (match.group(1), _MK_UNITS[match.group(2)])


