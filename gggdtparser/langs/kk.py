"""
哈萨克语
"""

ACCURATE_REGEX_LIST = []
FUZZY_REGEX_LIST = []

_KK_UNITS = {
    "секунд": "秒", "секундтан": "秒",
    "минут": "分钟", "минуттан": "分钟",
    "сағат": "小时", "сағаттан": "小时",
    "күн": "天", "күннен": "天",
    "апта": "周", "аптадан": "周",
    "ай": "月", "айдан": "月",
    "жыл": "年", "жылдан": "年",
}
_KK_UNIT_RE = (
    r"секунд(?:тан)?|минут(?:тан)?|сағат(?:тан)?|күн(?:нен)?|"
    r"апта(?:дан)?|ай(?:дан)?|жыл(?:дан)?"
)

_KK_WEEKDAYS = {
    "дүйсенбі": "周一",
    "сейсенбі": "周二",
    "сәрсенбі": "周三",
    "бейсенбі": "周四",
    "жұма": "周五",
    "сенбі": "周六",
    "жексенбі": "周日",
}

_KK_WEEKDAYS_RE = "|".join(sorted(_KK_WEEKDAYS, key=len, reverse=True))


def _kk_later(match):
    return "%s%s后" % (match.group(1), _KK_UNITS[match.group(2)])


def _kk_earlier(match):
    return "%s%s前" % (match.group(1), _KK_UNITS[match.group(2)])


