_BG_UNIT_RE = (
    r"секунда|секунди|минута|минути|час(?:а|ове)?|ден|дни|"
    r"седмица|седмици|месец(?:а|и)?|година|години"
)


def _bg_later(match):
    return "%s%s后" % (match.group(1), _BG_UNITS[match.group(2)])


def _bg_earlier(match):
    return "%s%s前" % (match.group(1), _BG_UNITS[match.group(2)])


