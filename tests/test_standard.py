# -*- coding: utf-8 -*-

import datetime

import pytest

from gggdtparser import parse


dt = datetime.datetime


def _local_timestamp_expected():
    return dt.fromtimestamp(1643738522)


VALID_CASES = [
    # 时间戳
    ("1643738522", _local_timestamp_expected()),
    ("1643738522000", _local_timestamp_expected()),
    # ISO / 分隔符 / 中文
    ("2022-02-02T02:02:02+00:00", dt(2022, 2, 2, 2, 2, 2)),
    ("2022-02-02 02:02:02", dt(2022, 2, 2, 2, 2, 2)),
    ("2022/02/02 02:02:02", dt(2022, 2, 2, 2, 2, 2)),
    ("2022年02月02日 02:02:02", dt(2022, 2, 2, 2, 2, 2)),
    ("20220202", dt(2022, 2, 2)),
    ("2022.02.02", dt(2022, 2, 2)),
    ("二零二二年二月二日", dt(2022, 2, 2)),
    ("2022/0202", dt(2022, 2, 2)),
    ("2022 02月02日", dt(2022, 2, 2)),
    # 年/月/日 的部分字段
    ("2022年02月", dt(2022, 2, 1)),
    ("2022/2", dt(2022, 2, 1)),
    ("2022.2", dt(2022, 2, 1)),
    ("2022年", dt(2022, 1, 1)),
    ("2022", dt(2022, 1, 1)),
    # 月/日/时/分/秒
    ("02月02日 02:02:02", dt(2026, 2, 2, 2, 2, 2)),
    ("02月02日 02:02", dt(2026, 2, 2, 2, 2)),
    ("02/02 02:02", dt(2026, 2, 2, 2, 2)),
    ("02月02日 02", dt(2026, 2, 2, 2)),
    ("02月02日", dt(2026, 2, 2)),
    ("02-02", dt(2026, 2, 2)),
    ("2/2", dt(2026, 2, 2)),
    ("02月", dt(2026, 2, 1)),
    ("02:02:02", dt(2026, 9, 18, 2, 2, 2)),
    ("02:02", dt(2026, 9, 18, 2, 2)),
    ("00:00", dt(2026, 9, 18, 0, 0)),
    ("12:05 am", dt(2026, 9, 18, 0, 5)),
    ("12:30 pm", dt(2026, 9, 18, 12, 30)),
    ("2022年5月25日，上午10:00", dt(2022, 5, 25, 10, 0)),
    ("2022年2月2日下午3时30分", dt(2022, 2, 2, 15, 30)),
    # 无零补齐与歧义顺序
    ("2023/2/20", dt(2023, 2, 20)),
    ("2023/2/15", dt(2023, 2, 15)),
    ("2023/2/25", dt(2023, 2, 25)),
    ("2023/3/10", dt(2023, 3, 10)),
    ("02-08-2022", dt(2022, 8, 2)),
    ("24/02/2022", dt(2022, 2, 24)),
    ("13-02-2022 02:19", dt(2022, 2, 13, 2, 19)),
    ("06-02-20", dt(2020, 2, 6)),
    ("2月 10, 2022", dt(2022, 2, 10)),
    ("2024-02-29", dt(2024, 2, 29)),
    # 噪声文本
    ("发布：2022/02/02 02:02:02，来源：xxx网", dt(2022, 2, 2, 2, 2, 2)),
    ("2022年02月02日\n  02:02:02", dt(2022, 2, 2, 2, 2, 2)),
]


@pytest.mark.parametrize("text,expected", VALID_CASES)
def test_parse_valid(base_dt, text, expected):
    assert parse(text, base_datetime=base_dt) == expected


INVALID_CASES = [
    "2023-02-31",
    "2023-02-30",
    "2022-13-01",
    "2022-00-01",
    "2022-02-00",
    "2022-02-02 24:00",
    "2022-02-02 25:61",
    "2023-02-31 12:30",
    "12345678",
]


@pytest.mark.parametrize("text", INVALID_CASES)
def test_parse_invalid(base_dt, text):
    assert parse(text, base_datetime=base_dt) is None
